"""Generate seed_postgres.sql from questions_data.py (S1-2.1)."""
from questions_data import QUESTIONS

def q(s):
    return "'" + s.replace("'", "''") + "'"

out = [
"-- Interview Studio - Sprint 1, Task S1-2.1 (US-2) - Author: Riket Sanketkumar Patel (GitHub: Riketpatel25)",
"-- Generated by generate_seed.py from questions_data.py. Safe to run multiple times.",
"",
"CREATE TABLE IF NOT EXISTS question_library (",
"    id                SERIAL PRIMARY KEY,",
"    category          TEXT NOT NULL,",
"    difficulty        TEXT NOT NULL,",
"    prompt            TEXT NOT NULL,",
"    expected_keywords TEXT[] NOT NULL DEFAULT '{}'",
");",
"",
"-- In case the table already exists from the init migration (S1-4.1)",
"ALTER TABLE question_library ADD COLUMN IF NOT EXISTS expected_keywords TEXT[] NOT NULL DEFAULT '{}';",
"CREATE UNIQUE INDEX IF NOT EXISTS question_library_prompt_uniq ON question_library (prompt);",
"",
"BEGIN;",
]
for cat, diff, prompt, kws in QUESTIONS:
    arr = "ARRAY[" + ", ".join(q(k) for k in kws) + "]::TEXT[]"
    out.append(f"INSERT INTO question_library (category, difficulty, prompt, expected_keywords) "
               f"VALUES ({q(cat)}, {q(diff)}, {q(prompt)}, {arr}) ON CONFLICT (prompt) DO NOTHING;")
out += [
"COMMIT;",
"",
"-- Validation: expect 50 technical rows (Easy 20 / Medium 20 / Hard 10, 5 per category)",
"SELECT COUNT(*) AS total FROM question_library WHERE difficulty IN ('Easy','Medium','Hard');",
"SELECT difficulty, COUNT(*) FROM question_library WHERE difficulty IN ('Easy','Medium','Hard') GROUP BY difficulty ORDER BY difficulty;",
"SELECT category, COUNT(*) FROM question_library WHERE difficulty IN ('Easy','Medium','Hard') GROUP BY category ORDER BY category;",
"",
]
open("seed_postgres.sql", "w").write("\n".join(out))
print("wrote", len(QUESTIONS), "questions")
