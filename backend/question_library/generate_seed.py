"""Generate seed_postgres.sql from questions_data.py, behavioral_data.py, and roles_data.py.

Run after migrations 001 and 003. The seed is safe to re-run on the live database:
- questions are matched by prompt and updated in place, never deleted (old answers point at their ids)
- skills and roles are upserted by name
- a role's role_skills rows, and a question's question_skills and rubric_criteria rows,
  are replaced on every run (nothing else points at them)
"""
import os
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, HERE)

from questions_data import QUESTIONS  # noqa: E402
from roles_data import ROLES, SKILLS  # noqa: E402

try:
    from behavioral_data import BEHAVIORAL_QUESTIONS  # S2-3.1, seeded once it merges
except ImportError:
    BEHAVIORAL_QUESTIONS = []


def q(s):
    """SQL string literal."""
    return "'" + str(s).replace("'", "''") + "'"


def arr(items):
    """SQL TEXT[] literal."""
    return "ARRAY[" + ", ".join(q(k) for k in items) + "]::TEXT[]"


def num(x):
    return format(x, "g")


def build():
    questions = list(QUESTIONS) + list(BEHAVIORAL_QUESTIONS)
    out = [
        "-- Interview Studio - Sprint 2, Task S2-1.4 (US-2) - Author: Riket Sanketkumar Patel (GitHub: Riketpatel25)",
        "-- Generated by generate_seed.py from questions_data.py, behavioral_data.py, and roles_data.py.",
        "-- Do not edit by hand. Run after migrations 001 and 003. Safe to run multiple times.",
        "",
        "-- ON CONFLICT (prompt) needs this index (Sprint 1 created it here too).",
        "CREATE UNIQUE INDEX IF NOT EXISTS question_library_prompt_uniq ON question_library (prompt);",
        "",
        "BEGIN;",
        "",
        f"-- Skills ({len(SKILLS)})",
    ]
    for name in SKILLS:
        out.append(f"INSERT INTO skills (name) VALUES ({q(name)}) ON CONFLICT (name) DO NOTHING;")

    out += ["", f"-- Roles ({len(ROLES)}) and their skill weights"]
    for r in ROLES:
        out.append(
            f"INSERT INTO roles (name, keywords, technical_share) "
            f"VALUES ({q(r['name'])}, {arr(r['keywords'])}, {num(r['technical_share'])}) "
            f"ON CONFLICT (name) DO UPDATE SET keywords = EXCLUDED.keywords, "
            f"technical_share = EXCLUDED.technical_share;"
        )
        role_id = f"(SELECT id FROM roles WHERE name = {q(r['name'])})"
        out.append(f"DELETE FROM role_skills WHERE role_id = {role_id};")
        for skill, weight in r["skills"].items():
            out.append(
                f"INSERT INTO role_skills (role_id, skill_id, weight) "
                f"SELECT {role_id}, s.id, {num(weight)} FROM skills AS s WHERE s.name = {q(skill)};"
            )

    out += ["", f"-- Questions ({len(questions)}), each with its skills and rubric"]
    for item in questions:
        prompt = item["prompt"]
        out.append(
            f"INSERT INTO question_library (category, difficulty, question_type, prompt, expected_keywords) "
            f"VALUES ({q(item['category'])}, {q(item['difficulty'])}, {q(item['question_type'])}, "
            f"{q(prompt)}, {arr(item['expected_keywords'])}) "
            f"ON CONFLICT (prompt) DO UPDATE SET category = EXCLUDED.category, "
            f"difficulty = EXCLUDED.difficulty, question_type = EXCLUDED.question_type, "
            f"expected_keywords = EXCLUDED.expected_keywords;"
        )
        qid = f"(SELECT id FROM question_library WHERE prompt = {q(prompt)})"
        out.append(f"DELETE FROM question_skills WHERE question_id = {qid};")
        for skill in item["skills"]:
            out.append(
                f"INSERT INTO question_skills (question_id, skill_id) "
                f"SELECT {qid}, s.id FROM skills AS s WHERE s.name = {q(skill)};"
            )
        out.append(f"DELETE FROM rubric_criteria WHERE question_id = {qid};")
        for pos, c in enumerate(item["rubric"], start=1):
            out.append(
                f"INSERT INTO rubric_criteria (question_id, position, text, keywords) "
                f"VALUES ({qid}, {pos}, {q(c['text'])}, {arr(c['keywords'])});"
            )
        out.append("")

    out += [
        "COMMIT;",
        "",
        "-- Validation",
        "SELECT question_type, difficulty, COUNT(*) FROM question_library "
        "GROUP BY question_type, difficulty ORDER BY question_type, difficulty;",
        "SELECT r.name, SUM(rs.weight) AS weight_total FROM roles AS r "
        "JOIN role_skills AS rs ON rs.role_id = r.id GROUP BY r.name ORDER BY r.name;",
        "SELECT COUNT(*) AS questions_without_rubric FROM question_library AS ql "
        "WHERE NOT EXISTS (SELECT 1 FROM rubric_criteria AS rc WHERE rc.question_id = ql.id);",
        "",
    ]
    return "\n".join(out), len(questions)


if __name__ == "__main__":
    sql, count = build()
    with open(os.path.join(HERE, "seed_postgres.sql"), "w") as f:
        f.write(sql)
    print("wrote", count, "questions,", len(ROLES), "roles,", len(SKILLS), "skills")
