"""S1-2.1 - Generate migrations/002_seed_questions.sql from app/data/questions_data.py.

Run from the backend folder:   python scripts/generate_seed_sql.py
The API also seeds automatically on startup, so this file is only needed if you
want to load the library by hand in the Supabase SQL Editor.
"""
from pathlib import Path
import sys

BACKEND = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(BACKEND))

from app.data.questions_data import QUESTIONS  # noqa: E402


def sql_str(s: str) -> str:
    return "'" + s.replace("'", "''") + "'"


def sql_array(items) -> str:
    return "ARRAY[" + ", ".join(sql_str(k) for k in items) + "]::TEXT[]"


def main() -> None:
    lines = [
        "-- S1-2.1 Sprint 1 technical question library (50 questions).",
        "-- GENERATED by scripts/generate_seed_sql.py from app/data/questions_data.py - do not edit by hand.",
        "-- Safe to re-run: existing prompts are skipped.",
        "",
        "INSERT INTO question_library (category, difficulty, prompt, expected_keywords) VALUES",
    ]
    rows = [
        f"  ({sql_str(c)}, {sql_str(d)}, {sql_str(p)}, {sql_array(k)})"
        for c, d, p, k in QUESTIONS
    ]
    lines.append(",\n".join(rows))
    lines.append("ON CONFLICT (prompt) DO NOTHING;")
    lines += [
        "",
        "-- Validation: expect 50 rows (Easy 20, Medium 20, Hard 10).",
        "SELECT difficulty, COUNT(*) FROM question_library GROUP BY difficulty ORDER BY difficulty;",
        "",
    ]
    out = BACKEND / "migrations" / "002_seed_questions.sql"
    out.write_text("\n".join(lines))
    print(f"Wrote {len(rows)} questions to {out}")


if __name__ == "__main__":
    main()
